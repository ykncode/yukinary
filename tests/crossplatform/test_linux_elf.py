#!/usr/bin/env python3
"""
test_linux_elf.py - Validates Linux x86-64 ELF64 binaries generated by Yukinary compiler.
Checks:
  1. ELF64 Header structure (Magic, Class, Endianness, Machine, Entrypoint)
  2. Program Header Table (PT_LOAD segment, virtual address, permissions)
  3. Linux _start Thunk ABI (argc/argv extraction, CALL ana, exit syscall 60)
  4. Native Syscall Emission (0x0F 0x05 for write, read, open, close, mmap, lseek)
"""

import argparse
import os
import struct
import subprocess
import sys

ROOT_DIR = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DEFAULT_COMPILER = os.path.join(ROOT_DIR, "build", "bootstrap", "stage0.exe")
COMPILER = DEFAULT_COMPILER
WORK_DIR = os.path.join(ROOT_DIR, "build", "test-work", "python-linux-elf")

TEST_CASES = [
    os.path.join(ROOT_DIR, "tests", "bootstrap", "01_hello.ykn"),
    os.path.join(ROOT_DIR, "tests", "bootstrap", "02_arithmetic.ykn"),
    os.path.join(ROOT_DIR, "tests", "bootstrap", "05_structs.ykn"),
    os.path.join(ROOT_DIR, "tests", "stdlib", "05_dosya.ykn"),
]

def compile_linux_elf(ykn_path, out_elf):
    if os.path.exists(out_elf):
        os.remove(out_elf)
    cmd = [COMPILER, "--target", "linux", ykn_path, out_elf]
    res = subprocess.run(cmd, cwd=ROOT_DIR, capture_output=True, text=True)
    if res.returncode != 0 or not os.path.exists(out_elf):
        print(f"[FAIL] Compilation failed for {ykn_path}: {res.stderr} {res.stdout}")
        return False
    return True

def validate_elf64_binary(elf_path):
    with open(elf_path, "rb") as f:
        data = f.read()

    if len(data) < 120:
        print(f"[FAIL] {elf_path}: File too small ({len(data)} bytes)")
        return False

    # 1. ELF Header (64 bytes)
    magic = data[:4]
    if magic != b"\x7fELF":
        print(f"[FAIL] Invalid ELF magic: {magic}")
        return False

    ei_class = data[4]    # 2 = 64-bit
    ei_data = data[5]     # 1 = Little Endian
    ei_version = data[6]  # 1

    if ei_class != 2 or ei_data != 1:
        print(f"[FAIL] Invalid ELF class/data: class={ei_class}, data={ei_data}")
        return False

    e_type, e_machine, e_version, e_entry, e_phoff, e_shoff, e_flags, e_ehsize, e_phentsize, e_phnum, e_shentsize, e_shnum, e_shstrndx = struct.unpack_from(
        "<HHIQQQIHHHHHH", data, 16
    )

    if e_type != 2: # ET_EXEC
        print(f"[FAIL] Expected ET_EXEC (2), got {e_type}")
        return False
    if e_machine != 0x3E: # EM_X86_64 (62)
        print(f"[FAIL] Expected EM_X86_64 (0x3E), got {e_machine:#x}")
        return False
    if e_phoff != 64:
        print(f"[FAIL] Expected e_phoff=64, got {e_phoff}")
        return False
    if e_phentsize != 56 or (e_phnum != 1 and e_phnum != 2):
        print(f"[FAIL] Expected 1 or 2 program headers of 56 bytes, got {e_phnum} of {e_phentsize} bytes")
        return False

    # 2. Program Header (56 bytes at offset 64)
    p_type, p_flags, p_offset, p_vaddr, p_paddr, p_filesz, p_memsz, p_align = struct.unpack_from(
        "<IIQQQQQQ", data, 64
    )

    if p_type != 1: # PT_LOAD
        print(f"[FAIL] Expected PT_LOAD (1), got {p_type}")
        return False
    if p_flags != 7: # PF_R | PF_W | PF_X
        print(f"[FAIL] Expected PF_R|PF_W|PF_X (7), got {p_flags}")
        return False
    if p_vaddr != 0x400000:
        print(f"[FAIL] Expected p_vaddr=0x400000, got {p_vaddr:#x}")
        return False

    # 3. Code offset and entrypoint verification
    code_start_offset = 64 + (56 * e_phnum)
    if e_entry < 0x400000 + code_start_offset:
        print(f"[FAIL] Entrypoint {e_entry:#x} is before code segment start")
        return False

    entry_file_offset = e_entry - 0x400000
    if entry_file_offset >= len(data):
        print(f"[FAIL] Entrypoint file offset {entry_file_offset} exceeds file size {len(data)}")
        return False

    # 4. Verify Linux _start thunk bytes (34 bytes):
    # 48 8B 0C 24          -> MOV RCX, [RSP]  (argc)
    # 48 8D 54 24 08       -> LEA RDX, [RSP+8] (argv)
    # 48 83 EC 20          -> SUB RSP, 32 (shadow space)
    # E8 xx xx xx xx       -> CALL ana
    # 48 83 C4 20          -> ADD RSP, 32
    # 48 89 C7             -> MOV RDI, RAX
    # 48 C7 C0 3C 00 00 00 -> MOV RAX, 60 (SYS_exit)
    # 0F 05                -> SYSCALL
    thunk = data[entry_file_offset:entry_file_offset + 34]
    if len(thunk) < 34:
        print(f"[FAIL] Thunk truncated (len={len(thunk)})")
        return False

    if thunk[0:4] != b"\x48\x8B\x0C\x24" or thunk[4:9] != b"\x48\x8D\x54\x24\x08" or thunk[9:13] != b"\x48\x83\xEC\x20" or thunk[13] != 0xE8:
        print(f"[FAIL] _start thunk prologue mismatch: {thunk.hex()}")
        return False

    if thunk[18:22] != b"\x48\x83\xC4\x20" or thunk[22:25] != b"\x48\x89\xC7" or thunk[25:32] != b"\x48\xC7\xC0\x3C\x00\x00\x00" or thunk[32:34] != b"\x0F\x05":
        print(f"[FAIL] _start thunk exit syscall mismatch: {thunk.hex()}")
        return False

    # 5. Syscall occurrences in binary
    syscall_count = data.count(b"\x0F\x05")
    if syscall_count == 0:
        print(f"[FAIL] No syscalls (0x0F 0x05) found in binary")
        return False

    print(f"[PASS] {os.path.basename(elf_path)}: Valid ELF64 (size={len(data)}B, entry={e_entry:#x}, syscalls={syscall_count})")
    return True

def main():
    global COMPILER
    parser = argparse.ArgumentParser(description="Validate generated Linux ELF64 artifacts")
    parser.add_argument("--compiler", default=DEFAULT_COMPILER,
                        help="Compiler path, relative to the project root or absolute")
    args = parser.parse_args()
    COMPILER = os.path.abspath(args.compiler if os.path.isabs(args.compiler)
                               else os.path.join(ROOT_DIR, args.compiler))
    if not os.path.isfile(COMPILER):
        print(f"[FAIL] Compiler not found: {COMPILER}")
        return 1
    os.makedirs(WORK_DIR, exist_ok=True)

    print("=" * 60)
    print("  YUKINARY CROSS-PLATFORM LINUX ELF64 VALIDATION SUITE")
    print("=" * 60)

    passed = 0
    total = len(TEST_CASES)

    for ykn in TEST_CASES:
        name = os.path.splitext(os.path.basename(ykn))[0]
        out_elf = os.path.join(WORK_DIR, f"{name}.elf")
        if compile_linux_elf(ykn, out_elf):
            if validate_elf64_binary(out_elf):
                passed += 1
        if os.path.exists(out_elf):
            os.remove(out_elf)

    print("-" * 60)
    print(f"Results: {passed}/{total} tests passed")
    if passed == total:
        print("ALL LINUX ELF64 CROSS-PLATFORM TESTS PASSED! [OK]")
        return 0
    else:
        print("SOME TESTS FAILED.")
        return 1

if __name__ == "__main__":
    sys.exit(main())
