#!/usr/bin/env python3
"""
test_arm64_elf.py - Validates Linux ARM64 ELF64 and macOS ARM64 Mach-O binaries generated by Yukinary compiler.
Checks:
  1. Linux ARM64 ELF64 Header structure (EM_AARCH64 = 0xB7, 64-bit Little Endian)
  2. Linux ARM64 _start thunk (LDR X0, [SP], ADD X1, SP, #8, BL ana, MOVZ X8, #93, SVC #0)
  3. macOS ARM64 Mach-O Header (CPU_TYPE_ARM64 = 0x0100000C, LC_SEGMENT_64, LC_UNIXTHREAD flavor 6)
  4. macOS ARM64 _start thunk (BL ana, MOVZ X16, #1, SVC #0x80)
"""

import argparse
import os
import struct
import subprocess
import sys

ROOT_DIR = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DEFAULT_COMPILER = os.path.join(ROOT_DIR, "build", "bootstrap", "stage0.exe")
COMPILER = DEFAULT_COMPILER
WORK_DIR = os.path.join(ROOT_DIR, "build", "test-work", "python-arm64")

TEST_CASES = [
    os.path.join(ROOT_DIR, "tests", "bootstrap", "01_hello.ykn"),
    os.path.join(ROOT_DIR, "tests", "bootstrap", "02_arithmetic.ykn"),
]

def compile_target(ykn_path, out_bin, target):
    if os.path.exists(out_bin):
        os.remove(out_bin)
    cmd = [COMPILER, "--target", target, ykn_path, out_bin]
    res = subprocess.run(cmd, cwd=ROOT_DIR, capture_output=True, text=True)
    if res.returncode != 0 or not os.path.exists(out_bin):
        print(f"[FAIL] Compilation failed for {ykn_path} (target={target}): {res.stderr} {res.stdout}")
        return False
    return True

def validate_linux_arm64(elf_path):
    with open(elf_path, "rb") as f:
        data = f.read()

    if len(data) < 120:
        print(f"[FAIL] {elf_path}: File too small")
        return False

    magic = data[:4]
    if magic != b"\x7fELF":
        print(f"[FAIL] Invalid ELF magic: {magic}")
        return False

    e_type, e_machine, e_version, e_entry = struct.unpack_from("<HHIQ", data, 16)
    if e_type != 2:
        print(f"[FAIL] Expected ET_EXEC (2), got {e_type}")
        return False
    if e_machine != 0xB7: # EM_AARCH64 (183)
        print(f"[FAIL] Expected EM_AARCH64 (0xB7), got {e_machine:#x}")
        return False

    entry_offset = e_entry - 0x400000
    thunk = data[entry_offset:entry_offset + 20]
    # LDR X0, [SP] = 0xE0 0x03 0x40 0xF9
    # ADD X1, SP, #8 = 0xE1 0x23 0x00 0x91
    # BL ana (0x94......)
    # MOVZ X8, #93 = 0xA8 0x0B 0x80 0xD2
    # SVC #0 = 0x01 0x00 0x00 0xD4
    if thunk[0:4] != b"\xE0\x03\x40\xF9" or thunk[4:8] != b"\xE1\x23\x00\x91":
        print(f"[FAIL] Linux ARM64 _start thunk prologue mismatch: {thunk.hex()}")
        return False
    if thunk[12:16] != b"\xA8\x0B\x80\xD2" or thunk[16:20] != b"\x01\x00\x00\xD4":
        print(f"[FAIL] Linux ARM64 exit SVC mismatch: {thunk.hex()}")
        return False

    print(f"[PASS] {os.path.basename(elf_path)}: Valid Linux ARM64 ELF (entry={e_entry:#x}, EM_AARCH64=0xB7)")
    return True

def validate_macos_arm64(macho_path):
    with open(macho_path, "rb") as f:
        data = f.read()

    if len(data) < 320:
        print(f"[FAIL] {macho_path}: File too small")
        return False

    magic, cputype, cpusubtype, filetype, ncmds, sizeofcmds, flags, reserved = struct.unpack_from(
        "<IIIIIIII", data, 0
    )
    if magic != 0xFEEDFACF:
        print(f"[FAIL] Invalid Mach-O 64 magic: {magic:#x}")
        return False
    if cputype != 0x0100000C: # CPU_TYPE_ARM64
        print(f"[FAIL] Expected CPU_TYPE_ARM64 (0x0100000C), got {cputype:#x}")
        return False

    # Dynamic command iteration for LC_MAIN or LC_UNIXTHREAD
    pos = 32
    entry_file_offset = None
    for _ in range(ncmds):
        if pos + 8 > len(data):
            break
        cmd, cmdsize = struct.unpack_from("<II", data, pos)
        if cmd == 0x80000028: # LC_MAIN
            entry_file_offset, = struct.unpack_from("<Q", data, pos + 8)
        elif cmd == 0x05: # LC_UNIXTHREAD
            entry_pc, = struct.unpack_from("<Q", data, pos + 16 + 256)
            entry_file_offset = entry_pc - 0x100000000
        pos += cmdsize

    if entry_file_offset is None or entry_file_offset >= len(data):
        print(f"[FAIL] Invalid entry point offset in {macho_path}")
        return False

    thunk = data[entry_file_offset:entry_file_offset + 28]
    # Modern LC_MAIN thunk:
    # CMP X0, #0     = 0x1F 0x00 0x00 0xF1
    # B.NE +16       = 0x81 0x00 0x00 0x54
    # LDR X0, [SP]   = 0xE0 0x03 0x40 0xF9
    # ADD X1, SP, #8 = 0xE1 0x23 0x00 0x91
    # BL ana (0x94......)
    # MOVZ X16, #1   = 0x30 0x00 0x80 0xD2
    # SVC #0x80      = 0x01 0x10 0x00 0xD4
    is_modern = (thunk[0:4] == b"\x1F\x00\x00\xF1" and thunk[4:8] == b"\x81\x00\x00\x54")
    is_legacy = (thunk[0:4] == b"\xE0\x03\x40\xF9" and thunk[4:8] == b"\xE1\x23\x00\x91")

    if not (is_modern or is_legacy):
        print(f"[FAIL] macOS ARM64 _start thunk prologue mismatch: {thunk[:16].hex()}")
        return False

    if is_modern:
        exit_code = thunk[20:28]
    else:
        exit_code = thunk[12:20]

    if exit_code != b"\x30\x00\x80\xD2\x01\x10\x00\xD4":
        print(f"[FAIL] macOS ARM64 exit SVC mismatch: {exit_code.hex()}")
        return False

    print(f"[PASS] {os.path.basename(macho_path)}: Valid macOS ARM64 Mach-O (entry={entry_file_offset:#x}, CPU_TYPE_ARM64=0x0100000C)")
    return True

def main():
    global COMPILER
    parser = argparse.ArgumentParser(description="Validate generated ARM64 artifacts")
    parser.add_argument("--compiler", default=DEFAULT_COMPILER,
                        help="Compiler path, relative to the project root or absolute")
    args = parser.parse_args()
    COMPILER = os.path.abspath(args.compiler if os.path.isabs(args.compiler)
                               else os.path.join(ROOT_DIR, args.compiler))
    if not os.path.isfile(COMPILER):
        print(f"[FAIL] Compiler not found: {COMPILER}")
        return 1
    os.makedirs(WORK_DIR, exist_ok=True)

    print("=" * 60)
    print("  YUKINARY CROSS-PLATFORM ARM64 VALIDATION SUITE")
    print("=" * 60)

    passed = 0
    total = len(TEST_CASES) * 2

    for ykn in TEST_CASES:
        name = os.path.splitext(os.path.basename(ykn))[0]
        # Linux ARM64
        out_elf = os.path.join(WORK_DIR, f"{name}_arm64.elf")
        if compile_target(ykn, out_elf, "linux-arm64"):
            if validate_linux_arm64(out_elf):
                passed += 1
        if os.path.exists(out_elf):
            os.remove(out_elf)

        # macOS ARM64
        out_macho = os.path.join(WORK_DIR, f"{name}_arm64.macho")
        if compile_target(ykn, out_macho, "macos-arm64"):
            if validate_macos_arm64(out_macho):
                passed += 1
        if os.path.exists(out_macho):
            os.remove(out_macho)

    print("-" * 60)
    print(f"Results: {passed}/{total} tests passed")
    if passed == total:
        print("ALL ARM64 CROSS-PLATFORM TESTS PASSED! [OK]")
        return 0
    else:
        print("SOME TESTS FAILED.")
        return 1

if __name__ == "__main__":
    sys.exit(main())
