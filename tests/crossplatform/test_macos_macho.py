#!/usr/bin/env python3
"""
test_macos_macho.py - Validates macOS x86-64 Mach-O 64 binaries generated by Yukinary compiler.
Supports both modern macOS (LC_PAGEZERO + LC_SEGMENT_64 + LC_BUILD_VERSION + LC_MAIN)
and legacy (LC_SEGMENT_64 + LC_UNIXTHREAD) layouts.
"""

import argparse
import os
import struct
import subprocess
import sys

ROOT_DIR = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DEFAULT_COMPILER = os.path.join(ROOT_DIR, "build", "stage2.exe")
if not os.path.exists(DEFAULT_COMPILER):
    DEFAULT_COMPILER = os.path.join(ROOT_DIR, "app_full.exe")
COMPILER = DEFAULT_COMPILER
WORK_DIR = os.path.join(ROOT_DIR, "build", "test-work", "python-macos-macho")

TEST_CASES = [
    os.path.join(ROOT_DIR, "tests", "bootstrap", "01_hello.ykn"),
    os.path.join(ROOT_DIR, "tests", "bootstrap", "02_arithmetic.ykn"),
    os.path.join(ROOT_DIR, "tests", "bootstrap", "05_structs.ykn"),
    os.path.join(ROOT_DIR, "tests", "stdlib", "05_dosya.ykn"),
]

def compile_macos_macho(ykn_path, out_macho):
    if os.path.exists(out_macho):
        os.remove(out_macho)
    cmd = [COMPILER, "--target", "macos", ykn_path, out_macho]
    res = subprocess.run(cmd, cwd=ROOT_DIR, capture_output=True, text=True)
    if res.returncode != 0 or not os.path.exists(out_macho):
        print(f"[FAIL] Compilation failed for {ykn_path}: {res.stderr} {res.stdout}")
        return False
    return True

def validate_macho64_binary(macho_path):
    with open(macho_path, "rb") as f:
        data = f.read()

    if len(data) < 304:
        print(f"[FAIL] {macho_path}: File too small ({len(data)} bytes)")
        return False

    # 1. Mach-O 64 Header (32 bytes)
    magic, cputype, cpusubtype, filetype, ncmds, sizeofcmds, flags, reserved = struct.unpack_from(
        "<IIIIIIII", data, 0
    )

    if magic != 0xFEEDFACF: # MH_MAGIC_64
        print(f"[FAIL] Invalid Mach-O 64 magic: {magic:#x}")
        return False
    if cputype != 0x01000007: # CPU_TYPE_X86_64
        print(f"[FAIL] Expected CPU_TYPE_X86_64 (0x01000007), got {cputype:#x}")
        return False
    if filetype != 2: # MH_EXECUTE
        print(f"[FAIL] Expected MH_EXECUTE (2), got {filetype}")
        return False

    # 2. Iterate load commands
    pos = 32
    entry_file_offset = None
    has_text_segment = False

    for _ in range(ncmds):
        if pos + 8 > len(data):
            break
        cmd, cmdsize = struct.unpack_from("<II", data, pos)
        if cmd == 0x19: # LC_SEGMENT_64
            segname = struct.unpack_from("<16s", data, pos + 8)[0].split(b"\x00")[0].decode("ascii", errors="ignore")
            if segname == "__TEXT":
                has_text_segment = True
        elif cmd == 0x80000028: # LC_MAIN
            # entryoff at offset 8 (uint64)
            entry_file_offset, = struct.unpack_from("<Q", data, pos + 8)
        elif cmd == 0x05: # LC_UNIXTHREAD
            # RIP at offset 16 + 128 = 144
            entry_rip, = struct.unpack_from("<Q", data, pos + 144)
            entry_file_offset = entry_rip - 0x100000000
        pos += cmdsize

    if not has_text_segment:
        print(f"[FAIL] Missing __TEXT segment in Mach-O")
        return False

    if entry_file_offset is None or entry_file_offset >= len(data):
        print(f"[FAIL] Invalid entry point offset: {entry_file_offset}")
        return False

    # 3. Verify macOS _start thunk bytes (46 bytes):
    # 48 85 FF             -> TEST RDI, RDI
    # 75 0C                -> JNZ +12 (has_args)
    # 48 8B 7C 24 00       -> MOV RDI, [RSP]
    # 48 8D 74 24 08       -> LEA RSI, [RSP+8]
    # 48 89 F9             -> MOV RCX, RDI
    # 48 89 F2             -> MOV RDX, RSI
    # 48 83 EC 20          -> SUB RSP, 32
    # E8 xx xx xx xx       -> CALL ana
    # 48 83 C4 20          -> ADD RSP, 32
    # 48 89 C7             -> MOV RDI, RAX
    # 48 C7 C0 01 00 00 02 -> MOV RAX, 0x2000001 (SYS_exit in macOS BSD)
    # 0F 05                -> SYSCALL
    thunk = data[entry_file_offset:entry_file_offset + 46]
    if len(thunk) < 46:
        print(f"[FAIL] Thunk truncated (len={len(thunk)})")
        return False

    prologue_expected = (
        b"\x48\x85\xFF\x75\x0C\x48\x8B\x7C\x24\x00\x48\x8D\x74\x24\x08"
        b"\x48\x89\xF9\x48\x89\xF2\x48\x83\xEC\x20\xE8"
    )
    if thunk[0:26] != prologue_expected:
        print(f"[FAIL] macOS _start thunk prologue mismatch: {thunk[0:26].hex()}")
        return False

    epilogue_expected = (
        b"\x48\x83\xC4\x20\x48\x89\xC7\x48\xC7\xC0\x01\x00\x00\x02\x0F\x05"
    )
    if thunk[30:46] != epilogue_expected:
        print(f"[FAIL] macOS _start thunk exit syscall mismatch: {thunk[30:46].hex()}")
        return False

    # 4. BSD Syscall checks (0x2000001 exit, 0x2000004 write, 0x0F 0x05)
    syscall_count = data.count(b"\x0F\x05")
    if syscall_count == 0:
        print(f"[FAIL] No syscalls (0x0F 0x05) found in binary")
        return False

    print(f"[PASS] {os.path.basename(macho_path)}: Valid Mach-O 64 (size={len(data)}B, entry_off={entry_file_offset:#x}, syscalls={syscall_count})")
    return True

def main():
    global COMPILER
    parser = argparse.ArgumentParser(description="Validate generated macOS Mach-O artifacts")
    parser.add_argument("--compiler", default=DEFAULT_COMPILER,
                        help="Compiler path, relative to the project root or absolute")
    args = parser.parse_args()
    COMPILER = os.path.abspath(args.compiler if os.path.isabs(args.compiler)
                               else os.path.join(ROOT_DIR, args.compiler))
    if not os.path.isfile(COMPILER):
        print(f"[FAIL] Compiler not found: {COMPILER}")
        return 1
    os.makedirs(WORK_DIR, exist_ok=True)

    print("=" * 60)
    print("  YUKINARY CROSS-PLATFORM MACOS MACH-O 64 VALIDATION SUITE")
    print("=" * 60)

    passed = 0
    total = len(TEST_CASES)

    for ykn in TEST_CASES:
        name = os.path.splitext(os.path.basename(ykn))[0]
        out_macho = os.path.join(WORK_DIR, f"{name}.macho")
        if compile_macos_macho(ykn, out_macho):
            if validate_macho64_binary(out_macho):
                passed += 1
        if os.path.exists(out_macho):
            os.remove(out_macho)

    print("-" * 60)
    print(f"Results: {passed}/{total} tests passed")
    if passed == total:
        print("ALL MACOS MACH-O 64 CROSS-PLATFORM TESTS PASSED! [OK]")
        return 0
    else:
        print("SOME TESTS FAILED.")
        return 1

if __name__ == "__main__":
    sys.exit(main())
