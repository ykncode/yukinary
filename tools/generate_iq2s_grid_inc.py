#!/usr/bin/env python3
"""Generate the compact IQ2_S grid include used by the native kernel."""
from __future__ import annotations

import base64
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / "std" / "ai" / "iq2s_grid.ykn").read_text(encoding="utf-8")
alt = [0] * 1024
upper = [0] * 1024
pattern = re.compile(r"IQ2S_GRID_(ALT|UST)\[(\d+)\]\s*=\s*(\d+)\s*;")
for kind, index_text, value_text in pattern.findall(source):
    target = alt if kind == "ALT" else upper
    target[int(index_text)] = int(value_text)
if any(value == 0 for value in alt) or any(value == 0 for value in upper):
    raise SystemExit("IQ2_S grid tablosu eksik")

mapping = {8: 0, 25: 1, 43: 2}
packed = bytearray()
for index in range(1024):
    lanes = [((word >> shift) & 0xFF) for word in (alt[index], upper[index]) for shift in (0, 8, 16, 24)]
    value = 0
    for lane, item in enumerate(lanes):
        if item not in mapping:
            raise SystemExit(f"beklenmeyen IQ2_S grid değeri: {item}")
        value |= mapping[item] << (lane * 2)
    packed.extend(value.to_bytes(2, "little"))

encoded = base64.b64encode(packed).decode("ascii")
out = ROOT / "libykn" / "llm_iq2s_grid.inc"
out.write_text(
    "// Generated by tools/generate_iq2s_grid_inc.py; do not edit manually.\n"
    "static constexpr char YKN_IQ2S_GRID_BASE64[] =\n"
    + "\n".join(f'    \"{encoded[i:i + 96]}\"' for i in range(0, len(encoded), 96))
    + ";\n",
    encoding="utf-8",
)
print(f"generated {out} ({len(packed)} packed bytes)")
